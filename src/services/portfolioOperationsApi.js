import Api from './api';

/**
 * Phase 8.0 — Portfolio Operations API
 *
 * All execute requests use only previewId + Idempotency-Key.
 * No action IDs or payload are sent on execute — the server loads the
 * operation from the stored preview record.
 */

export const PortfolioOperationsApi = {

  /**
   * POST /api/portfolio/operations/preview
   * @param {object} params - { operation, mode, actionIds, payload }
   */
  async previewBulkOperation({ operation, mode, actionIds, payload }) {
    return Api.post('/api/portfolio/operations/preview', {
      operation,
      mode,
      actionIds,
      payload,
    });
  },

  /**
   * POST /api/portfolio/operations/:previewId/execute
   * Sends ONLY the previewId (in URL) and Idempotency-Key (in header).
   * No action IDs or payload in the body.
   * @param {string} previewId       - UUID from preview response
   * @param {string} idempotencyKey  - UUID v4 generated by caller
   */
  async executeBulkOperation(previewId, idempotencyKey) {
    const token = Api.getToken();
    const headers = {
      'Content-Type': 'application/json',
      'Idempotency-Key': idempotencyKey,
    };
    if (token) headers['Authorization'] = `Bearer ${token}`;

    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 30000);

    let res;
    try {
      res = await fetch(`/api/portfolio/operations/${encodeURIComponent(previewId)}/execute`, {
        method: 'POST',
        headers,
        signal: controller.signal,
      });
    } catch (fetchErr) {
      clearTimeout(timer);
      if (fetchErr.name === 'AbortError') {
        throw new Error('Request timed out. Please check your network or try again.');
      }
      throw fetchErr;
    }
    clearTimeout(timer);

    const contentType = res.headers.get('content-type') || '';
    const data = contentType.includes('application/json') ? await res.json() : await res.blob();

    if (!res.ok) {
      const message = (data && data.error) || 'Execute failed';
      const err = new Error(message);
      err.status = res.status;
      err.code = data && data.code;
      err.data = data;
      throw err;
    }
    return data;
  },

  /**
   * GET /api/portfolio/operations/history
   * @param {object} params - { page, limit }
   */
  async getBatchHistory({ page = 1, limit = 20 } = {}) {
    const qs = new URLSearchParams({ page, limit }).toString();
    return Api.get(`/api/portfolio/operations/history?${qs}`);
  },

  /**
   * GET /api/portfolio/operations/pending-approvals
   * @param {object} params - { page, limit }
   */
  async getPendingApprovals({ page = 1, limit = 20 } = {}) {
    const qs = new URLSearchParams({ page, limit }).toString();
    return Api.get(`/api/portfolio/operations/pending-approvals?${qs}`);
  },

  /**
   * POST /api/portfolio/operations/:batchId/approve
   * @param {string} batchId
   * @param {string} comments
   */
  async approveBatch(batchId, comments = '') {
    return Api.post(`/api/portfolio/operations/${encodeURIComponent(batchId)}/approve`, { comments });
  },

  /**
   * POST /api/portfolio/operations/:batchId/reject
   * @param {string} batchId
   * @param {string} reason
   */
  async rejectBatch(batchId, reason) {
    return Api.post(`/api/portfolio/operations/${encodeURIComponent(batchId)}/reject`, { reason });
  },
};

export default PortfolioOperationsApi;
